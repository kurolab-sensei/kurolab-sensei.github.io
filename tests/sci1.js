// 記号の組み合わせを選択肢にする（正解の組と、まぎらわしい組を3つ）
function comboCh(r, letters, right) {
  const key = a => a.slice().sort().join("・");
  const all = [];
  for (let m = 1; m < (1 << letters.length); m++) {
    const s = letters.filter((_, i) => m >> i & 1);
    if (s.length <= 3) all.push(key(s));
  }
  const rk = key(right);
  const near = all.filter(k => k !== rk).sort((a, b) => Math.abs(a.length - rk.length) - Math.abs(b.length - rk.length) || (r() - 0.5));
  return { right: rk, wrongs: near.slice(0, 6).sort(() => r() - 0.5).slice(0, 3) };
}
