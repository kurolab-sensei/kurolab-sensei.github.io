/* ---------- グラフを描く共通関数 ---------- */
function graph({ w = 330, h = 230, xmax, ymax, xstep, ystep, xlabel, ylabel, series, xticks, yticks }) {
  const L = 46, B = h - 36, R = w - 12, T = 12;
  const X = v => L + (R - L) * v / xmax, Y = v => B - (B - T) * v / ymax;
  let s = "";
  for (let v = 0; v <= xmax + 1e-9; v += xstep) s += line(X(v), T, X(v), B, 'stroke="#bbb" stroke-width="0.6"');
  for (let v = 0; v <= ymax + 1e-9; v += ystep) s += line(L, Y(v), R, Y(v), 'stroke="#bbb" stroke-width="0.6"');
  s += line(L, B, R, B) + line(L, B, L, T);
  for (let v = 0; v <= xmax + 1e-9; v += xticks || xstep) s += `<text x="${X(v)}" y="${B + 14}" text-anchor="middle" font-size="11">${v}</text>`;
  for (let v = 0; v <= ymax + 1e-9; v += yticks || ystep) s += `<text x="${L - 5}" y="${Y(v) + 4}" text-anchor="end" font-size="11">${v}</text>`;
  s += `<text x="${(L + R) / 2}" y="${h - 4}" text-anchor="middle" font-size="12">${xlabel}</text>`;
  s += `<text x="10" y="${(T + B) / 2}" text-anchor="middle" font-size="12" transform="rotate(-90 10 ${(T + B) / 2})">${ylabel}</text>`;
  for (const sr of series) {
    s += `<polyline fill="none" stroke="#222" stroke-width="${sr.wd || 1.8}" ${sr.dash ? 'stroke-dasharray="5 3"' : ""} points="${sr.pts.map(([a, b]) => X(a) + "," + Y(b)).join(" ")}"/>`;
    if (sr.label) { const [a, b] = sr.at || sr.pts[sr.pts.length - 1]; s += `<text x="${X(a) + 4}" y="${Y(b) - 4}" font-weight="700">${sr.label}</text>`; }
  }
  return svg(w, h, s);
}

